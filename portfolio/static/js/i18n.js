/** Idiomas do menu: [código, nome no próprio idioma]. Só listar idiomas com tradução completa. */
export const LANGS = [
  ["pt", "Português"],
  ["en", "English"],
  ["es", "Español"],
  ["fr", "Français"],
  ["no", "Norsk"],
];

/** Idioma inicial: o último escolhido; senão o do navegador (se existir aqui); senão português. */
const salvo = (() => {
  try {
    return localStorage.getItem("lang");
  } catch {
    return null;
  }
})();
const doNavegador = (navigator.language || "pt").slice(0, 2).toLowerCase();
const inicial =
  [salvo, doNavegador].find((c) => LANGS.some(([k]) => k === c)) ?? "pt";

/** Idioma atual (objeto, para ser compartilhado entre módulos). */
export const state = { lang: inicial };
/** Texto da interface no idioma atual (cai para inglês se faltar). */
export const t = (k) => (T[state.lang] && T[state.lang][k]) ?? T.en[k];
/** Escolher a tradução de um campo {pt, en, ...}; texto simples aparece igual em todos os idiomas. */
export const loc = (o) =>
  typeof o === "string" ? o : (o[state.lang] ?? o.en ?? o.pt);
